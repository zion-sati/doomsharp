using System.Buffers.Binary;
using System.Text;
using DoomSharp;

// Keeps every lump name in order and the data of the lumps one benchmark run
// reads: by name, and the selected map's lumps. Other lumps become empty.
// usage: Reducer <source WAD> <bench directory>; writes e1m1.wad and
// WadData.g.cs there.
byte[] source = File.ReadAllBytes(args[0]);
Wad wad = new(source);
string map = wad.Maps.First();
Game game = new(wad, map);
Renderer renderer = new();
int checksum = 0;
for (int i = 0; i < 120; i++)
{
    renderer.Render(game);
    checksum = unchecked(checksum * 31 + renderer.Pixels[(i * 7919) % renderer.Pixels.Length]);
}
int marker = wad.Lumps.FindLastIndex(l => l.Name == map);
HashSet<int> keep = [];
for (int i = marker; i < wad.Lumps.Count && (i == marker || !Wad.IsMap(wad.Lumps[i].Name)); i++) keep.Add(i);
for (int i = 0; i < wad.Lumps.Count; i++)
    if (Wad.Accessed.Contains(wad.Lumps[i].Name)) keep.Add(i);
using MemoryStream data = new();
List<(int Offset, int Length, string Name)> directory = [];
foreach (var (lump, index) in wad.Lumps.Select((l, i) => (l, i)))
{
    byte[] bytes = keep.Contains(index) ? lump.Data : [];
    directory.Add(((int)data.Position + 12, bytes.Length, lump.Name));
    data.Write(bytes);
}
byte[] output = new byte[12 + data.Length + directory.Count * 16];
Encoding.ASCII.GetBytes("IWAD").CopyTo(output, 0);
BinaryPrimitives.WriteInt32LittleEndian(output.AsSpan(4), directory.Count);
BinaryPrimitives.WriteInt32LittleEndian(output.AsSpan(8), 12 + (int)data.Length);
data.ToArray().CopyTo(output, 12);
for (int i = 0; i < directory.Count; i++)
{
    int entry = 12 + (int)data.Length + i * 16;
    BinaryPrimitives.WriteInt32LittleEndian(output.AsSpan(entry), directory[i].Offset);
    BinaryPrimitives.WriteInt32LittleEndian(output.AsSpan(entry + 4), directory[i].Length);
    Encoding.ASCII.GetBytes(directory[i].Name.PadRight(8, '\0')).CopyTo(output, entry + 8);
}
File.WriteAllBytes(Path.Combine(args[1], "e1m1.wad"), output);

// The bench compiles the WAD in as UTF-8 base64 literals, which a NetWasm
// module keeps as static data, so it needs no file access.
const int ChunkLength = 1_000_000;
string base64 = Convert.ToBase64String(output);
int chunks = (base64.Length + ChunkLength - 1) / ChunkLength;
StringBuilder code = new();
code.Append("// Generated by tools/NetWasmBench/Reducer: the reduced E1M1 WAD, base64 in UTF-8 literals (stored as static data).\n")
    .Append("static class WadData\n{\n    public static byte[] Bytes()\n    {\n")
    .Append("        var text = new System.Text.StringBuilder();\n");
for (int i = 0; i < chunks; i++)
    code.Append("        text.Append(System.Text.Encoding.ASCII.GetString(Chunk").Append(i).Append("));\n");
code.Append("        return Convert.FromBase64String(text.ToString());\n    }\n");
for (int i = 0; i < chunks; i++)
    code.Append("    static ReadOnlySpan<byte> Chunk").Append(i).Append(" => \"")
        .Append(base64, i * ChunkLength, Math.Min(ChunkLength, base64.Length - i * ChunkLength)).Append("\"u8;\n");
code.Append("}\n");
File.WriteAllText(Path.Combine(args[1], "WadData.g.cs"), code.ToString());
Console.WriteLine($"checksum {checksum} lumps {wad.Lumps.Count} kept {keep.Count} bytes {output.Length}");
